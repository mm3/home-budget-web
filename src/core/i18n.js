const BUNDLED = { en: EN, ru: RU, de: DE };

/** All translation keys, in the order they are defined in English. */
export function translationKeys() {
  return Object.keys(EN);
}

/** Texts of a bundled language, or an empty object. */
export function bundledTexts(language) {
  return BUNDLED[language] || {};
}

/** Picks the best bundled language for a browser language list. */
export function detectLanguage(browserLanguages = []) {
  for (const tag of browserLanguages) {
    const code = String(tag).toLowerCase().split('-')[0];
    if (BUNDLED[code]) return code;
  }
  return DEFAULT_LANGUAGE;
}

/**
 * Builds a translate function.
 * @param {string} language 'en', 'ru', 'de' or 'custom'
 * @param {object} [custom] user supplied texts, used when language is 'custom'
 * @returns {(key: string, params?: object) => string}
 */
export function createTranslator(language, custom = {}) {
  const texts = language === CUSTOM_LANGUAGE ? custom : bundledTexts(language);
  return (key, params) => {
    const template = (texts && texts[key]) || EN[key] || key;
    return params ? fill(template, params) : template;
  };
}

/**
 * The month and week names periodLabel needs, in the current language.
 * @param {(key: string) => string} t a translator from createTranslator
 */
export function periodTexts(t) {
  return {
    months: Array.from({ length: 12 }, (unused, index) => t(`month.${index + 1}`)),
    week: t('periodLabel.week'),
    weekShort: t('periodLabel.weekShort'),
  };
}

/** Replaces {name} placeholders. */
export function fill(template, params) {
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

/** Keeps only known keys with non-empty string values. */
export function sanitizeTranslation(raw) {
  const clean = {};
  if (!raw || typeof raw !== 'object') return clean;
  for (const key of translationKeys()) {
    const value = raw[key];
    if (typeof value === 'string' && value.trim()) clean[key] = value;
  }
  return clean;
}
